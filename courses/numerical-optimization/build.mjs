// Usage: node build.mjs --katex /absolute/path/to/katex.mjs
// Build-time only: the generated site uses native MathML and has no runtime dependencies.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const arg=process.argv.indexOf('--katex');
const katex=arg>=0?(await import(pathToFileURL(path.resolve(process.argv[arg+1])).href)).default:(await import('katex')).default;
const context={window:{}}; vm.createContext(context);
const files=fs.readdirSync(path.join(root,'content')).filter(f=>/^ch\d+\.js$/.test(f)).sort();
for(const file of files)vm.runInContext(fs.readFileSync(path.join(root,'content',file),'utf8'),context,{filename:file});
let count=0;
function render(s){return s.replace(/\\\[([\s\S]*?)\\\]|\\\(([\s\S]*?)\\\)/g,(_,display,inline)=>{
  const block=display!==undefined;
  const html=katex.renderToString(block?display:inline,{displayMode:block,output:'mathml',throwOnError:true,strict:'error',trust:false});
  count++;return `<${block?'div':'span'} class="math-${block?'block':'inline'}">${html}</${block?'div':'span'}>`;
});}
const chapters=context.window.OPT_CHAPTERS;
const ids=new Set();
for(const c of chapters)for(const s of c.sections){const id=c.id+'/'+s.id;if(ids.has(id))throw Error('Duplicate route: '+id);ids.add(id);s.body=render(s.body);}
fs.writeFileSync(path.join(root,'chapters.js'),'// Generated by build.mjs. Edit content/ch*.js, not this file.\nwindow.OPT_CHAPTERS = '+JSON.stringify(chapters,null,2)+';\n');
// A changed local asset gets a stable content hash so a refresh cannot mix old chapters with new demos.
const entry=path.join(root,'index.html');
const html=fs.readFileSync(entry,'utf8').replace(/((?:src|href)=")([\w-]+\.(?:js|css))(?:\?v=[^"]*)?"/g,(_,prefix,name)=>{
  const hash=createHash('sha256').update(fs.readFileSync(path.join(root,name))).digest('hex').slice(0,12);
  return `${prefix}${name}?v=${hash}"`;
});
fs.writeFileSync(entry,html);
console.log(`Built ${chapters.length} chapters, ${ids.size} sections, ${count} formulas.`);
