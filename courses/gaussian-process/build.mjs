import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
import content from './content-source.mjs';
// Pass the installed KaTeX module explicitly; no network dependency is shipped.
const modulePath=process.argv[2];
if(!modulePath)throw Error('Usage: node build.mjs /absolute/path/to/katex.mjs');
const {default:katex}=await import(pathToFileURL(path.resolve(modulePath)));
let count=0;
const render=(s,displayMode)=>{count++;return katex.renderToString(s,{displayMode,output:'mathml',throwOnError:true,strict:'error'});};
const sections=content({eq:s=>`<div class="equation">${render(s,true)}</div>`,inline:s=>render(s,false)});
const ids=new Set();for(const s of sections){if(ids.has(s.id))throw Error('Duplicate id');ids.add(s.id);}
fs.writeFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)),'content.js'),'/* Generated by build.mjs; edit content-source.mjs. */\nwindow.GP_CONTENT='+JSON.stringify(sections,null,2)+';\n');
console.log(`${sections.length} sections, ${count} equations compiled to offline MathML.`);
